# Oral-B uses a 128-bit base UUID whose tail spells "PGMS" + "Oral-B":
#   A0F0xxxx-5047-4D53-8208-4F72616C2D42
BASE_UUID = "a0f0{short}-5047-4d53-8208-4f72616c2d42"


def oralb_uuid(short: str) -> str:
    """Return the full 128-bit UUID for a 16-bit Oral-B short UUID."""
    return BASE_UUID.format(short=short.lower())


